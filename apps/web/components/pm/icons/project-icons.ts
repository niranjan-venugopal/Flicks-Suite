export const HEX_COLOR_RE = /^#[0-9a-fA-F]{6}$/

/** `lucide:<name>` with a name in the curated set. */
export function isLucideIcon(value: string | null | undefined): value is `lucide:${string}` {
  return typeof value === 'string' && value.startsWith(PROJECT_ICON_PREFIX) && value.slice(PROJECT_ICON_PREFIX.length) in GLYPHS
}

/** Any `lucide:` value, curated or not (an unknown name draws the default glyph). */
export function looksLikeLucideIcon(value: string | null | undefined): boolean {
  return typeof value === 'string' && /^lucide:[a-z0-9-]{1,24}$/.test(value)
}

/** The React component for a `lucide:<name>` value; the default glyph for unknown names; null for emoji / empty. */
export function lucideComponent(value: string | null | undefined): LucideGlyph | null {
  if (!looksLikeLucideIcon(value)) return null
  const name = (value as string).slice(PROJECT_ICON_PREFIX.length)
  return GLYPHS[name] ?? GLYPHS['folder-kanban']
}

/** Human label for a curated name: "folder-kanban" → "Folder kanban". */
export function iconLabel(name: string): string {
  const bare = name.startsWith(PROJECT_ICON_PREFIX) ? name.slice(PROJECT_ICON_PREFIX.length) : name
  const words = bare.replace(/-/g, ' ')
  return words.charAt(0).toUpperCase() + words.slice(1)
}

/** Stable swatch for a project that has none stored (hash of the name). */
export function defaultColorFor(seed: string | null | undefined): string {
  if (!seed) return DEFAULT_PROJECT_COLOR
  let h = 0
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0
  return PROJECT_COLORS[h % PROJECT_COLORS.length].value
}

/** Case-insensitive search over the curated set (name + label words). */
export function searchProjectIcons(query: string): ReadonlyArray<{ group: string; icons: readonly string[] }> {
  const q = query.trim().toLowerCase()
  if (!q) return PROJECT_ICON_GROUPS
  return PROJECT_ICON_GROUPS.map((g) => ({
    group: g.group,
    icons: g.icons.filter((n) => n.includes(q) || iconLabel(n).toLowerCase().includes(q)),
  })).filter((g) => g.icons.length > 0)
}

/** A sanitised colour for rendering: the stored value when it is #RRGGBB, else the hashed default. */
export function tileColor(color: string | null | undefined, seed?: string | null): string {
  return color && HEX_COLOR_RE.test(color) ? color : defaultColorFor(seed)
}
