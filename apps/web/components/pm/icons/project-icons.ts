/**
 * Project icon library (Round P R5). A project's `icon` is either a legacy
 * emoji (6 stock glyphs from Round C, kept as-is) or `lucide:<name>` from
 * this curated set, drawn white on a colour tile (`color`, #RRGGBB). A
 * project shows EITHER its icon tile OR an uploaded image (`logo_key`):
 * choosing an icon clears the image on the server, uploading an image hides
 * the icon until "Remove image" — the icon + colour stay stored so they come
 * straight back.
 *
 * Only the curated names are imported (tree-shakable named imports — never
 * the `icons` catalogue, which is ~1,700 glyphs). The API (both the REST
 * DTOs and the service, which the offline-sync door calls directly) accepts
 * `lucide:[a-z0-9-]{1,24}` — any letter-case of the `lucide:` prefix must be
 * a well-formed lower-case name — or a 1–16 character emoji without
 * whitespace/control characters; `color` must be #RRGGBB. A curated-set miss
 * renders the default tile so an older client never breaks a newer server.
 */

export type LucideGlyph = ComponentType<
  SVGProps<SVGSVGElement> & { size?: number | string; strokeWidth?: number | string; absoluteStrokeWidth?: boolean }
>

